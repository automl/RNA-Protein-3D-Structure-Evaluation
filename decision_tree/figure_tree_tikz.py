"""
Fig. decision (TikZ): the reliability score as three outputs and their main inputs, drawn at text width so that its
type is not scaled down. Coefficients and RNA-only cut-offs are in the Supplementary tables. Leaf counts are the
2026 AlphaFold Server predictions at each level, read from the frozen design's test (calibration_probability.json and
probability/2026_*.tsv), so nothing is typed by hand.

Writes 2025_NAR_AF3_Evaluation/figures2/decision_tree/decision_tree_22.tex
Run:  python -m decision_tree.figure_tree_tikz
"""
from __future__ import annotations

import csv
import json
import os

_REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
CAL = os.path.join(_REPO, "decision_tree", "calibration_probability.json")
PROB = os.path.join(_REPO, "results", "plots", "all_chains", "decision_tree", "probability")
OUT = os.path.join(_REPO, "2025_NAR_AF3_Evaluation", "figures2", "decision_tree", "decision_tree_22.tex")

INPUT_NAMES = {
    "pae": r"intra-RNA PAE (AF3)", "multi_rna": r"$\geq$2 RNA chains", "tm_familiar": r"familiar fold of the AF3 model",
    "n_rbp_templates": r"RNA-bound protein templates", "seq_familiar": r"familiar RNA sequence",
    "pae_min": r"chain-pair PAE$_{\min}$ (AF3)", "partner_ptm": r"pTM$_p$ of the partner (AF3)",
    "plddt": r"pLDDT$_r$ (AF3)", "rbp_template": r"RNA-bound protein template", "familiar": r"familiar RNA",
    "wellfolded": r"well-folded partner",
}


def _counts(name):
    n = {"WEAK": 0, "MODERATE": 0, "STRONG": 0}
    for r in csv.DictReader(open(os.path.join(PROB, f"2026_{name}.tsv")), delimiter="\t"):
        if r["level"] in n:
            n[r["level"]] += 1
    return n


def _rna_only_counts(cal, key, branch, test):
    lv = cal[key][branch]["test_2026"][test]["levels"]
    return {k: v["n"] for k, v in lv.items()}


def _inputs(cal, side):
    return r"\\[1pt]".join(r"$\bullet$\ " + INPUT_NAMES.get(f, f) for f in cal[side]["features"])


def _leaves(node, x, y, n):
    return "\n".join(
        rf"\node[{style}, text width=1.5cm, font=\scriptsize\bfseries] ({node}{k}) at ({x + dx},{y}) {{{lv}\\\textit{{n}}\,=\,{n[lv]}}};"
        rf" \draw[ed] ({node}.south) -- ({node}{k}.north);"
        for k, (style, lv, dx) in enumerate((("leafL", "WEAK", -1.62), ("leafM", "MODERATE", 0.0), ("leafH", "STRONG", 1.62))))


def build():
    cal = json.load(open(CAL))
    nf, ni, nu = _counts("fold"), _counts("interface"), _counts("overall")
    ns = _rna_only_counts(cal, "rna_single", "without_alignment", "test_server")
    nm = _rna_only_counts(cal, "rna_multi", "without_alignment", "test_server")
    tex = rf"""% Decision figure (variant 22, for af3_final.tex): the reliability score as three outputs and their main inputs.
% Generated by decision_tree/figure_tree_tikz.py from calibration_probability.json and the 2026 test; do not edit by
% hand. Coefficients: Table tab:prob_coefficients; RNA-only cut-offs: Table tab:rna_subtrees. Leaves give the number of
% 2026 AlphaFold Server predictions at each level (WEAK < 25% <= MODERATE < 60% <= STRONG).
{{\sffamily
\begin{{tikzpicture}}[x=1cm,y=1cm, every node/.append style={{font=\footnotesize}}]
\node[root, text width=9.5cm, font=\small\bfseries] (top) at (8.2,9.15) {{AF3 prediction of an RNA or protein–RNA structure}};
\node[dec, text width=5.6cm, align=center, font=\small\bfseries] (q0) at (8.2,8.15) {{Protein chain in the prediction?}};
\draw[ed] (top) -- (q0);
\node[root, text width=8.6cm, font=\small\bfseries] (h) at (4.6,6.95) {{Protein–RNA prediction}};
\node[root, text width=4.4cm, font=\small\bfseries] (r) at (13.9,6.95) {{RNA-only prediction}};
\draw[ed] (q0) -- node[midway, above, font=\scriptsize] {{yes}} (h);
\draw[ed] (q0) -- node[midway, above, font=\scriptsize] {{no}} (r);

\node[dec, text width=4.0cm, anchor=north] (f) at (2.1,6.35) {{\textbf{{P$_{{\mathrm{{fold}}}}$}}\; RNA well folded\\[2pt]{_inputs(cal, "fold")}}};
\node[dec, text width=4.0cm, anchor=north] (i) at (7.35,6.35) {{\textbf{{P$_{{\mathrm{{interface}}}}$}}\; RNA placed correctly\\[2pt]{_inputs(cal, "interface")}}};
\node[dec, text width=4.0cm, anchor=north] (o) at (13.9,6.35) {{\textbf{{P$_{{\mathrm{{fold}}}}$}}\; RNA well folded\\[2pt]$\bullet$\ pLDDT$_r$ with an RNA alignment\\[1pt]$\bullet$\ intra-RNA PAE without one\\[1pt]$\bullet$\ RNA complexes: duplex in the model}};
\draw[ed] (h) -- (f); \draw[ed] (h) -- (i); \draw[ed] (r) -- (o);

{_leaves("f", 2.1, 3.2, nf)}
{_leaves("i", 7.35, 3.2, ni)}

\node[dec, text width=8.0cm, align=center] (u) at (4.7,1.75) {{\textbf{{P$_{{\mathrm{{usable}}}}$}}\; protein–RNA model reliable (RNA well folded and placed correctly)\\[1pt]P$_{{\mathrm{{fold}}}}$ and P$_{{\mathrm{{interface}}}}$ joined with correlation ${cal["overall"]["rho"]:.2f}$}};
\draw[ed] (f0.south) |- (u.west); \draw[ed] (i2.south) |- (u.east);
{_leaves("u", 4.7, 0.4, nu)}

\node[font=\scriptsize\bfseries] at (13.9,3.75) {{single RNA}};
{_leaves("o", 13.9, 3.2, ns).replace("(o0)", "(s0)").replace("(o1)", "(s1)").replace("(o2)", "(s2)").replace("o0.north", "s0.north").replace("o1.north", "s1.north").replace("o2.north", "s2.north").replace("(o0)", "(s0)")}
\node[font=\scriptsize\bfseries] at (13.9,2.25) {{RNA complex}};
\node[leafL, text width=1.5cm, font=\scriptsize\bfseries] (m0) at (12.28,1.7) {{WEAK\\\textit{{n}}\,=\,{nm["WEAK"]}}};
\node[leafM, text width=1.5cm, font=\scriptsize\bfseries] (m1) at (13.9,1.7) {{MODERATE\\\textit{{n}}\,=\,{nm["MODERATE"]}}};
\node[leafH, text width=1.5cm, font=\scriptsize\bfseries] (m2) at (15.52,1.7) {{STRONG\\\textit{{n}}\,=\,{nm["STRONG"]}}};
\node[font=\scriptsize, align=center] at (13.9,0.4) {{Each probability is WEAK below 25\%,\\MODERATE from 25\% to 60\%,\\STRONG from 60\%}};
\end{{tikzpicture}}%
}}
"""
    open(OUT, "w").write(tex)
    print("wrote", OUT, "| fold", nf, "interface", ni, "usable", nu, "single", ns, "complex", nm)



TABLE_OUT = os.path.join(PROB, "prob_coefficients_table.tex")
DESCR = {
    "pae": r"intra-RNA PAE of the longest RNA chain (\AA)", "multi_rna": r"$\geq2$ RNA chains in the model (yes $=1$)",
    "tm_familiar": r"familiar fold: AF3 model's longest RNA chain has a pre-cutoff RNA with TM$_r \geq 0.5$ (yes $=1$)",
    "n_rbp_templates": r"number of RNA-bound protein templates used by AF3",
    "pae_min": r"minimum chain-pair PAE between the RNA chain and a protein chain (\AA)",
    "partner_ptm": r"pTM$_p$ of that protein partner",
    "seq_familiar": r"familiar sequence: an RNA of a PDB entry released before 30 September 2021 with $\geq80\%$ identity (yes $=1$)",
    "rbp_template": r"AF3 used an RNA-bound protein template for any protein chain (yes $=1$)",
    "familiar": r"familiar RNA: familiar sequence or familiar fold (yes $=1$)",
    "wellfolded": r"well-folded partner: pTM$_p \geq 0.84$ and pLDDT$_r \geq 0.78$ (yes $=1$)",
}


def table():
    """Supplementary table: log-odds of the protein-RNA probabilities, with odds ratio per unit (or per answer)"""
    import math
    cal = json.load(open(CAL))
    rows = []
    for side, title in (("fold", r"P$_{\mathrm{fold}}$ (well-folded RNA)"), ("interface", r"P$_{\mathrm{interface}}$ (correct interface)")):
        d = cal[side]
        rows.append(rf"\multicolumn{{3}}{{l}}{{\emph{{{title}}}}}\\")
        rows.append(rf"\quad intercept & ${d['intercept']:+.3f}$ & \\")
        for f, c in d["coef"].items():
            rows.append(rf"\quad {DESCR.get(f, f)} & ${c:+.3f}$ & ${math.exp(c):.2f}$ \\")
    tex = r"""\begin{table}[!htbp]
\centering\color{red}
\begin{threeparttable}
\caption{\red{Log-odds of the protein–RNA probabilities. Each probability is $1/(1+e^{-z})$, where $z$ is the intercept plus the sum of coefficient times input. Odds ratios are per unit of a continuous input or for a yes answer. Inputs were selected by cross-validated forward selection on post-cutoff targets, and the weights were fitted on the same targets. The usable-chain probability joins P$_{\mathrm{fold}}$ and P$_{\mathrm{interface}}$ by a Gaussian copula with correlation $""" + f"{cal['overall']['rho']:.2f}" + r"""$.}}
\label{tab:prob_coefficients}
\setlength{\tabcolsep}{4pt}\renewcommand{\arraystretch}{1.12}
\begin{tabular}{p{9.2cm}rr}
\toprule
Input & Coefficient & Odds ratio \\
\midrule
""" + "\n".join(rows) + r"""
\bottomrule
\end{tabular}
\end{threeparttable}
\end{table}"""
    open(TABLE_OUT, "w").write(tex)
    print("wrote", TABLE_OUT)
    return tex


if __name__ == "__main__":
    build()
    table()
